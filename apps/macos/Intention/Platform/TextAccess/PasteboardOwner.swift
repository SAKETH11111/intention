import AppKit

/// The single owner of Intention's clipboard writes, used by the paste route
/// when a field ignores Accessibility writes.
///
/// A paste borrows the clipboard. When macOS lets Intention read other apps'
/// clipboard data without asking ("Paste from Other Apps" set to Allow),
/// Intention copies every item and type first and puts the copy back once the
/// field shows the pasted text, which proves the app has read it; restoring
/// earlier would let a slow app paste the person's own clipboard instead.
/// A copy is bound to the clipboard's change count: it is taken again when
/// the clipboard changes while being read, Intention writes only while that
/// count still holds, and restores only while its own write is still there.
/// Those checks run on the main actor without suspending, but are not atomic
/// with other apps.
///
/// Intention's write is bound to its change count too. `writeTransient` keeps
/// a count only when the clipboard still holds Intention's own write at it,
/// so a copy another app makes during the write ends the paste before any
/// key. The paste key is posted only while the clipboard is still at that
/// count (`stillHolds(_:)`), so a copy the person or another app made by
/// then ends the paste with no key. That check runs on the inserter's executor,
/// right before the key, and is not atomic with other apps either: a copy
/// made after it, while the key is prepared or before the app reads the
/// clipboard, is still what gets pasted.
///
/// Otherwise Intention does not read the clipboard at all: macOS would put a
/// prompt in front of the person mid-sentence, under Ask on every read. The
/// pasted text then stays on the clipboard. Either way Intention's text is
/// marked transient, so clipboard managers that follow the nspasteboard.org
/// conventions skip it.
@MainActor
final class PasteboardOwner {
    /// Every item on the clipboard with the data of each of its types.
    struct Snapshot: Sendable {
        fileprivate let items: [[ItemData]]
        /// False when a type declared on the clipboard returned no data,
        /// such as data its owner promised and could not supply.
        let complete: Bool
        /// The clipboard's change count while it was read.
        let changeCount: Int
    }

    enum Backup: Sendable {
        /// macOS would ask before Intention reads the clipboard, so it was not.
        case notAllowed
        case copied(Snapshot)
        /// The clipboard kept changing while Intention read it.
        case changing

        var snapshot: Snapshot? {
            if case let .copied(snapshot) = self { snapshot } else { nil }
        }
    }

    enum Write: Equatable, Sendable {
        /// The clipboard holds Intention's text, at this change count.
        case written(Int)
        /// The clipboard is not Intention's to paste from or restore over. Either
        /// it changed after the copy and Intention left it alone, or another app
        /// cleared it after Intention's write, and it holds that app's copy or
        /// soon will.
        case changed
        /// Intention cleared the clipboard and could not write its text. A copy
        /// goes back only through `putBack(_:)`.
        case failed
    }

    fileprivate struct ItemData: Sendable {
        let type: NSPasteboard.PasteboardType
        let data: Data
    }

    static let transientTypes: [NSPasteboard.PasteboardType] = [
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
    ]

    private let pasteboard: NSPasteboard
    private nonisolated let name: NSPasteboard.Name
    private let readRule: @MainActor () -> Bool
    private let put: @MainActor (NSPasteboard, NSPasteboardItem) -> Bool

    /// `mayRead` replaces the system's rule, and `put` the write of Intention's
    /// item to the cleared clipboard, for tests: the system offers no way
    /// to make that write fail.
    init(pasteboard: NSPasteboard = .general, mayRead: (@MainActor () -> Bool)? = nil,
         put: (@MainActor (NSPasteboard, NSPasteboardItem) -> Bool)? = nil) {
        self.pasteboard = pasteboard
        name = pasteboard.name
        readRule = mayRead ?? { [pasteboard] in Self.systemAllowsReading(pasteboard) }
        self.put = put ?? { $0.writeObjects([$1]) }
    }

    var changeCount: Int { pasteboard.changeCount }

    /// Whether a paste has the clipboard: from an insertion's backup until
    /// it is put back, or until a little after a paste that
    /// was not confirmed. The app being pasted into may read it at any
    /// moment in between. Each paste borrows and gives back once, so one
    /// paste's late timer never ends another's hold.
    var borrowed: Bool { borrowers > 0 }
    private var borrowers = 0

    func borrow() {
        borrowers += 1
    }

    func giveBack() {
        borrowers = max(0, borrowers - 1)
    }

    /// Whether Intention may read clipboard data from other apps without macOS
    /// asking the person. Before macOS 15.4 there is no such rule.
    var mayReadOtherApps: Bool { readRule() }

    /// For setup's Clipboard row, on the person's press: reads the clipboard
    /// once, off the main thread, so macOS asks and lists Intention under Paste
    /// from Other Apps, where the person can choose Allow. What it reads is
    /// dropped at once. It is the one read made while macOS would ask;
    /// insertion never reads then.
    func askToRead() async {
        guard !mayReadOtherApps else { return }
        let name = pasteboard.name
        await Task.detached {
            let pasteboard = NSPasteboard(name: name)
            _ = pasteboard.pasteboardItems?.first?.types.first.flatMap { pasteboard.data(forType: $0) }
        }.value
    }

    private static func systemAllowsReading(_ pasteboard: NSPasteboard) -> Bool {
        if #available(macOS 15.4, *) { return pasteboard.accessBehavior == .alwaysAllow }
        return true
    }

    /// A copy of the clipboard. The data is read off the main thread, since
    /// an app can take a while to supply a large or promised item, and read
    /// again if the clipboard changed meanwhile.
    func backUp() async -> Backup {
        guard mayReadOtherApps else { return .notAllowed }
        let name = pasteboard.name
        for _ in 0..<3 {
            let changeCount = pasteboard.changeCount
            let snapshot = await Task.detached { Self.read(NSPasteboard(name: name), changeCount: changeCount) }.value
            if pasteboard.changeCount == changeCount { return .copied(snapshot) }
        }
        return .changing
    }

    private nonisolated static func read(_ pasteboard: NSPasteboard, changeCount: Int) -> Snapshot {
        var complete = true
        let items = (pasteboard.pasteboardItems ?? []).map { item in
            item.types.compactMap { type -> ItemData? in
                guard let data = item.data(forType: type) else {
                    complete = false
                    return nil
                }
                return ItemData(type: type, data: data)
            }
        }
        return Snapshot(items: items, complete: complete, changeCount: changeCount)
    }

    /// Replaces the clipboard with `text` marked transient, unless it changed
    /// after the copy taken at `changeCount`. Without a copy, nil, the
    /// clipboard is replaced whatever it holds.
    ///
    /// The count is moved by each clearing, by Intention or any other app, and
    /// not by writing items or types after it. Only the app that made the
    /// latest clearing can write: once another app clears, Intention's writes
    /// fail and leave that app's clipboard as it is. So a write that
    /// succeeded, followed by a count equal to the one `clearContents()`
    /// returned, shows that the clipboard holds Intention's write at that
    /// count. Another count means another app cleared after the write, and
    /// the clipboard holds that app's copy or soon will. The count
    /// `clearContents()` returns is not by itself Intention's: when two apps
    /// clear at once both can be given the later one, but Intention's write
    /// then fails.
    ///
    /// What remains open: a copy another app makes after Intention's last read
    /// of the count is left to `stillHolds(_:)` before the key, and one made
    /// after that is pasted. A copy made just before Intention's clearing is
    /// erased by it. Two processes are never atomic.
    func writeTransient(_ text: String, html: String? = nil, ifUnchangedSince changeCount: Int?) -> Write {
        if let changeCount, pasteboard.changeCount != changeCount { return .changed }
        let cleared = pasteboard.clearContents()
        let item = NSPasteboardItem()
        guard item.setString(text, forType: .string) else { return .failed }
        if let html, !item.setString(html, forType: .html) { return .failed }
        for type in Self.transientTypes { item.setData(Data(), forType: type) }
        guard put(pasteboard, item) else { return .failed }
        guard pasteboard.changeCount == cleared else { return .changed }
        return .written(cleared)
    }

    /// A check that the clipboard still holds Intention's write numbered
    /// `changeCount`, for the inserter to make on its own executor as the
    /// last thing before the paste key. It reads the change count only,
    /// which is not clipboard data: `writeTransient` reads the same count
    /// after its write whether or not Intention may read the clipboard, so this
    /// is read off the main actor and under any Paste from Other Apps rule,
    /// through a pasteboard of the same name, as `backUp()` reads its data.
    /// Another app can still write between this answer and the key; the
    /// check shortens that window and does not close it.
    nonisolated func stillHolds(_ changeCount: Int) -> @Sendable () -> Bool {
        let name = name
        return { NSPasteboard(name: name).changeCount == changeCount }
    }

    /// Puts `snapshot` back unless the clipboard changed after Intention's write
    /// numbered `changeCount`. Returns whether all of it was restored.
    ///
    /// It keeps no count of its own, since nothing after it relies on one,
    /// and the check and the clearing are not atomic: a copy another app
    /// makes between them is erased. One made between the clearing and the
    /// write makes the write fail, so that copy stays and the result is
    /// false; one made after the write replaces the restored copy with the
    /// result still true. An empty copy writes nothing after the clearing,
    /// so it reads as restored whatever another app copied since.
    @discardableResult
    func restore(_ snapshot: Snapshot, ifUnchangedSince changeCount: Int) -> Bool {
        guard pasteboard.changeCount == changeCount else { return false }
        pasteboard.clearContents()
        let items = Self.items(of: snapshot)
        return (items.isEmpty || pasteboard.writeObjects(items)) && snapshot.complete
    }

    /// Puts `snapshot` back after `writeTransient` cleared the clipboard and
    /// then failed to write, without clearing it again. No count tells
    /// Intention's clearing from another app's: one that clears just before
    /// Intention moves Intention's clearing a count further, and one that clears
    /// just after can be given the same count Intention was. A write without a
    /// clearing lands only for the app that made the latest clearing, so
    /// the copy comes back to a clipboard Intention still holds, and a copy
    /// another app has made since, or is about to make, is left as it is.
    /// An empty copy needs no write: Intention's clearing already left the
    /// clipboard empty.
    ///
    /// It adds to the clearing rather than replacing it, so it is right
    /// only when nothing of Intention's landed on that clearing. Its one caller
    /// is `writeTransient`'s failed write of a single item filled before the
    /// write, where a failure has written nothing. A writer of several
    /// items, a custom `NSPasteboardWriting` or a data provider can leave
    /// part of its write behind and must not use it as it is.
    func putBack(_ snapshot: Snapshot) {
        let items = Self.items(of: snapshot)
        if !items.isEmpty { _ = pasteboard.writeObjects(items) }
    }

    private static func items(of snapshot: Snapshot) -> [NSPasteboardItem] {
        snapshot.items.map { types in
            let item = NSPasteboardItem()
            for entry in types { item.setData(entry.data, forType: entry.type) }
            return item
        }
    }

    /// Puts text the person asked to copy, such as a dictation from
    /// history, on the clipboard as ordinary text they own. Returns whether
    /// it was written.
    /// Refused while a paste has the clipboard, so the app being pasted into
    /// can never receive this text instead. It keeps no count either: a copy
    /// another app makes between the clearing and the write makes the write
    /// fail and return false, and one made after the write replaces it.
    ///
    /// `concealed` marks the copy with the nspasteboard.org concealed type,
    /// for words that may be a password, so clipboard managers that follow
    /// the convention do not keep them.
    @discardableResult
    func copy(_ text: String, concealed: Bool = false) -> Bool {
        guard !borrowed else { return false }
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        if concealed { item.setData(Data(), forType: Self.concealedType) }
        return pasteboard.writeObjects([item])
    }

    static let concealedType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
}

#if DEBUG
/// Only the Debug checks persist a clipboard snapshot, in their private
/// crash recovery file. Release builds keep clipboard data in memory.
extension PasteboardOwner.Snapshot: Codable {
    private struct StoredItem: Codable {
        let type: String
        let data: Data
    }

    private enum CodingKeys: String, CodingKey { case items, complete, changeCount }

    init(from decoder: Decoder) throws {
        let values = try decoder.container(keyedBy: CodingKeys.self)
        items = try values.decode([[StoredItem]].self, forKey: .items).map { item in
            item.map { PasteboardOwner.ItemData(type: NSPasteboard.PasteboardType($0.type), data: $0.data) }
        }
        complete = try values.decode(Bool.self, forKey: .complete)
        changeCount = try values.decode(Int.self, forKey: .changeCount)
    }

    func encode(to encoder: Encoder) throws {
        var values = encoder.container(keyedBy: CodingKeys.self)
        try values.encode(items.map { item in item.map { StoredItem(type: $0.type.rawValue, data: $0.data) } }, forKey: .items)
        try values.encode(complete, forKey: .complete)
        try values.encode(changeCount, forKey: .changeCount)
    }

    /// Recovery distinguishes a complete restore from a partial write and
    /// treats transient text as a paste that may still be awaiting its app.
    var checkIsEmpty: Bool { complete && items.isEmpty }

    var checkIsTransient: Bool {
        items.contains { item in
            item.contains { ["org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"].contains($0.type.rawValue) }
        }
    }

    func checkMatches(_ other: Self) -> Bool {
        complete && other.complete && items.elementsEqual(other.items) { left, right in
            left.elementsEqual(right) { $0.type == $1.type && $0.data == $1.data }
        }
    }

    var checkString: String? {
        items.first?.first { $0.type == .string }.flatMap { String(data: $0.data, encoding: .utf8) }
    }
}
#endif
